#!/usr/bin/env bash
# Print DIGEST.md: every text file of the repository in one document, with line numbers, so an AI assistant or a reader
# without repository access sees exactly the same content (including the exact line numbers the results refer to).
# Usage: tools/make_digest.sh > DIGEST.md   (CI checks that DIGEST.md is up to date)
set -euo pipefail
cd "$(dirname "$0")/.."
echo "# DIGEST: certify-the-checker (all text files, generated by tools/make_digest.sh)"
echo
echo "Line numbers are shown for every file. The bug lines in examples/*/example.env refer to these numbers."
for f in llms.txt README.md CHANGELOG.md STANDARD-v0.md examples/expected-results.txt $(LC_ALL=C ls -d examples/*/ | sed 's|/$||' | while read -r d; do echo "$d/example.env $d/target.c $d/harness.c"; done) \
         tools/run_all.sh tools/run_example.sh tools/readout.py tools/validate_readout.py tools/support/gcov_dump_on_crash.c \
         schema/readout.schema.json readout-template.json Dockerfile .github/workflows/examples.yml CONTRIBUTING.md PROVENANCE.md LICENSES.md; do
  echo
  echo "## FILE: $f"
  echo
  echo '```'
  awk '{printf "%4d  %s\n", NR, $0}' "$f"
  echo '```'
done
